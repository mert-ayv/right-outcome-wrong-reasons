"""Score H2b derivations on the twins against each twin's own solver steps (descriptive, not pre-registered).

Rebuilds every twin's case from the original case and the twin's edit, checks that the solver
reproduces the twin's label, and reports per run: twin-consistent accuracy (pre-registered
co-primary), fully correct derivations on originals and twins, how often an operative twin cites the
same steps as its original, and the operative twins of originals whose derivation was fully correct.

Usage: python -I src/twin_derivations.py --records results/h2b/records --out results/h2b/twin_derivations.md
"""
import argparse
import json
import os
import sys
from datetime import datetime, timedelta

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from proof_steps_v2 import full_derivation_correct, gold_steps_v2, parse_steps_v2  # noqa: E402

RUNS = ["h2b-base", "h2b-sft-step100", "h2b-outcome-s1-step120", "h2b-process-s1-step120",
        "h2b-outcome-s2-step120", "h2b-process-s2-step120"]


def twin_case(case, tw):
    ds = sorted(case["domicile_dates"].items())
    d, s = ds[tw["edited_index"]]
    ds[tw["edited_index"]] = ((datetime.fromisoformat(d) + timedelta(days=tw["shift_days"])).isoformat(), s)
    return dict(case, domicile_dates=dict(ds))


def correct(pred, gold):
    return pred is not None and sorted(pred) == sorted(gold)


def pct(v):
    return f"{100 * sum(v) / len(v):.0f}%" if v else ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", default="data/test.jsonl")
    ap.add_argument("--records", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    test = [json.loads(l) for l in open(args.test)]
    for r in test:
        r["steps"] = gold_steps_v2(r["case"])[0]
        for tw in r["twins"]:
            tw["steps"], ans = gold_steps_v2(twin_case(r["case"], tw))
            assert sorted(ans) == sorted(tw["answer"]), r["id"]
    rows = []
    for tag in RUNS:
        recs = {x["id"]: x for x in map(json.loads, open(f"{args.records}/{tag}.jsonl"))}
        consistent, fd_orig, fd_inv, fd_op, same_steps, cond_deriv, cond_ans = [], [], [], [], [], [], []
        for r in test:
            x = recs[r["id"]]
            consistent.append(correct(x["pred"], r["answer"]) and
                              all(correct(y["pred"], tw["answer"]) for y, tw in zip(x["twins"], r["twins"])))
            orig_ok = full_derivation_correct(x["text"], r["steps"])
            fd_orig.append(orig_ok)
            for y, tw in zip(x["twins"], r["twins"]):
                ok = full_derivation_correct(y["text"], tw["steps"])
                if tw["kind"] == "invariant":
                    fd_inv.append(ok)
                    continue
                fd_op.append(ok)
                same_steps.append(parse_steps_v2(y["text"]) == parse_steps_v2(x["text"]))
                if orig_ok:
                    cond_deriv.append(ok)
                    cond_ans.append(correct(y["pred"], tw["answer"]))
        rows.append(f"| {tag} | {pct(consistent)} | {pct(fd_orig)} | {pct(fd_inv)} | {pct(fd_op)} | {pct(same_steps)} "
                    f"| {sum(cond_deriv)}/{len(cond_deriv)} | {sum(cond_ans)}/{len(cond_ans)} |")
    with open(args.out, "w") as f:
        f.write("# Derivations on the twins (H2b)\n\nGenerated by `src/twin_derivations.py`. Twin-consistent accuracy is "
                "pre-registered; the other columns are descriptive. A derivation is fully correct if it scores 1.0 "
                "against the solver's steps for that exact case (original or twin).\n\n"
                "| Run | Twin-consistent accuracy | Fully correct derivation: original | invariant twin | operative twin "
                "| Operative twin cites the same steps as its original | Operative twins of a fully correct original: "
                "derivation correct | answer correct |\n|---|---|---|---|---|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
    print(open(args.out).read())


if __name__ == "__main__":
    main()
