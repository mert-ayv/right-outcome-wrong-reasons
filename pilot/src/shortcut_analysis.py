"""Which simple rule of thumb do a model's answers follow? (descriptive, not pre-registered)

For each test case, five shortcut rules pick a state from the domicile history; the answer is then
completed with the opt-out rule. The script reports how often each shortcut is legally correct, and
how often each model's answers coincide with it.

Usage: python -I src/shortcut_analysis.py --test data/test.jsonl \
           --run base=results/rerun_modal/records/base.jsonl --run sft=... --out results/shortcut_analysis.md
"""
import argparse
import json
from datetime import datetime, timedelta

OPTED_OUT = {"ARIZONA", "ILLINOIS"}


def answer_for(state):
    return [state.title()] if state in OPTED_OUT else sorted(["Federal", state.title()])


def shortcuts(case):
    p = datetime.fromisoformat(case["petition_date"])
    ds = sorted((datetime.fromisoformat(k), v) for k, v in case["domicile_dates"].items())
    w = p - timedelta(days=730)
    days = {}
    for i, (d, s) in enumerate(ds):
        nxt = ds[i + 1][0] if i + 1 < len(ds) else p
        a = max(d, w)
        if (nxt - a).days > 0:
            days[s] = days.get(s, 0) + (nxt - a).days
    picks = {
        "first state named": ds[0][1],
        "state on day 730 before the petition": [s for d, s in ds if d <= w][-1],
        "longest stay in the last 730 days": max(days, key=days.get),
        "second-to-last state": ds[-2][1] if len(ds) > 1 else ds[-1][1],
        "current state (last move)": ds[-1][1],
    }
    return {k: answer_for(v) for k, v in picks.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", required=True)
    ap.add_argument("--run", action="append", default=[], help="name=path to records jsonl")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    test = {r["id"]: r for r in map(json.loads, open(args.test))}
    sc = {i: shortcuts(r["case"]) for i, r in test.items()}
    names = list(next(iter(sc.values())).keys())
    legal = {k: sum(sc[i][k] == sorted(test[i]["answer"]) for i in test) / len(test) for k in names}
    runs = {}
    for spec in args.run:
        name, path = spec.split("=", 1)
        recs = [json.loads(l) for l in open(path)]
        runs[name] = {"acc": sum(r["pred"] == sorted(r["gold"]) for r in recs) / len(recs),
                      **{k: sum(r["pred"] == sc[r["id"]][k] for r in recs) / len(recs) for k in names}}
    lines = ["| Shortcut rule | Legally correct | " + " | ".join(f"Agrees with {n}" for n in runs) + " |",
             "|---|---|" + "---|" * len(runs)]
    for k in names:
        lines.append(f"| {k} | {legal[k]:.0%} | " + " | ".join(f"{runs[n][k]:.0%}" for n in runs) + " |")
    lines.append("| *(model accuracy)* | | " + " | ".join(f"{runs[n]['acc']:.0%}" for n in runs) + " |")
    text = "\n".join(lines)
    with open(args.out, "w") as f:
        f.write("# Shortcut analysis (descriptive, not pre-registered)\n\nGenerated by `src/shortcut_analysis.py`.\n\n" + text + "\n")
    print(text)


if __name__ == "__main__":
    main()
